// 1. 万能头文件，包含了所有标准库（竞赛常用）
#include <bits/stdc++.h>
// 2. 引入标准命名空间，省得每次写 std::
using namespace std;

// 4. 主函数，signed main() 是为了防止某些环境下 main 返回值溢出（竞赛习惯写法）
signed main()
{
    // 6. 定义两个整数 n 和 k
    int n, k;
    // 7. 从标准输入读取 n 和 k
    cin >> n >> k;

    // 8. 定义一个整型 vector（动态数组），大小为 n。
    // 此时里面是未初始化的垃圾值，或者可以被覆盖的值。
    vector<int> a(n);

    // 9-12. 循环初始化 vector。
    // i 从 0 到 n-1，我们让 a[i] = i + 1。
    // 这样就得到了初始序列：1, 2, 3, ..., n
    for (int i = 0; i < n; i++)
    {
        a[i] = i + 1;
    }

    // 13-18. 循环 k 次，执行 k 个咒语。
    // while(k--) 的意思是：先做 k 次循环，每次循环结束后 k 减 1，直到 k 变为 0。
    while (k--)
    {
        // 15. 定义左右端点 l 和 r
        int l, r;
        // 16. 读入当前的左右端点
        cin >> l >> r;

        // 17. 核心操作：反转区间。
        // a.begin() 是指向数组第一个元素的迭代器（指针）。
        // a.begin() + l - 1 将指针移动到第 l 个元素的位置（因为索引从0开始）。
        // a.begin() + r 将指针移动到第 r+1 个元素的位置（作为 end）。
        // reverse 会把 [l-1, r) 这个左闭右开区间内的元素反转。
        // 也就是题目要求的第 l 到第 r 个元素反转。
        reverse(a.begin() + l - 1, a.begin() + r);
    }

    // 19-26. 输出最终结果。
    for (int i = 0; i < n; i++)
    {
        // 21-24. 控制输出格式，除了第一个元素（i=0），后面每个元素前面加一个空格。
        if (i > 0)
        {
            cout << " ";
        }
        // 25. 输出当前元素
        cout << a[i];
    }
    // 27. 输出换行符
    cout << endl;

    // 28-29. 程序正常结束，返回 0。
    return 0;
}
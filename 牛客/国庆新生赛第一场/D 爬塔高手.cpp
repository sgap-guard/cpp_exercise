#include <bits/stdc++.h>    // 万能头文件
using namespace std;        // 引入标准命名空间

#define int long long       // 宏定义：把所有的 int 替换成 long long
// 目的：防止方案数太多导致 int 溢出（通常题目要求对 1e9+7 取模，结果可能很大）

signed main()               // 主函数，signed 对应 long long 的别名
{
    int n, cnt = 0; cin >> n; // 读入怪物血量 n，初始化计数器 cnt 为 0

    // --- 开始双重循环枚举 ---
    // 枚举第一种牌（3点伤害）的数量 i
    for (int i = 0; i * 3 <= n; i++)  // i 从 0 开始，只要 3*i 不超过总血量 n 就继续
    {
        // 枚举第二种牌（4点伤害）的数量 j
        // 注意：这里是在 i 确定的基础上枚举 j，保证了组合的唯一性（类似百鸡问题中先买公鸡再买母鸡的顺序）
        for (int j = 0; i * 3 + j * 4 <= n; j++)
        {
            // 计算用完 i 张3点和 j 张4点后，还剩下多少血量
            static long long r = n - 3 * i - 4 * j;

            // 判断剩下的血量 r 是否能恰好被 7 整除（即能否用若干张7点牌打掉）
            if (r >= 0 && r % 7 == 0)
            {
                cnt++; // 如果能凑齐，方案数加 1

                // 题目通常要求结果对 1000000007 取模，这里进行防溢出处理
                if (cnt >= 1000000007)
                {
                    cnt -= 1000000007;
                }
            }
        }
    }

    // 输出最终符合条件的方案总数，再次确保取模（保险起见）
    cout << cnt % 1000000007 << endl;
    return 0;
}
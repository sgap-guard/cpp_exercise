#include<bits/stdc++.h> // 【万能头文件】包含了C++几乎所有的标准库。竞赛中为了节省写头文件的时间，通常直接用它。
#define int long long  // 【宏定义】将代码中所有的 int 替换成 long long。因为原题数据累加可能达到 5e14，普通 int 会溢出。
using namespace std;   // 【命名空间】防止标准库名字冲突，竞赛常用写法。

const int maxn = 500005; // 【常量定义】根据题目 n <= 5e5 的范围，多开一点点（+5），防止边缘越界。
long long a[maxn], d[maxn]; // 【全局数组】极其关键！写在 main 外面有三个好处：
                           // 1. 自动初始化为0（这保证了 a[0] = 0，计算 d[1] = a[1] - a[0] 时不会出错）
                           // 2. 存放在全局数据区，空间很大，不会像局部变量那样发生“栈溢出”
                           // 3. 所有函数（虽然这里只有一个）都能访问。

signed main() // 【主函数】为什么写 signed 而不是 int？因为上面宏定义了 `#define int long long`，
              // 编译器会把 `int main()` 替换成 `long long main()`，这在C++标准里是不允许的。
              // 写 `signed main()` 就能完美避开宏替换，且等价于 `int main()`。
{
    int n, q; // n是数组长度，q是操作次数。因为宏定义，这里 n 和 q 实际上也是 long long 类型。
    cin >> n >> q; // 读入 n 和 q。注意：如果数据量特别大（比如1e6），建议加上 ios::sync_with_stdio(false); 来加速。

    // 【构建差分数组】
    for (int i = 1; i <= n; i++) // 题目下标从1开始，所以我们从1遍历到n
    {
        cin >> a[i]; // 读入原数组
        // 【差分核心公式】d[i] = a[i] - a[i-1]
        // 为什么要这么写？差分数组记录的是相邻元素的“增量”。
        // 当 a[0] 为0时，d[1] = a[1]，d[2] = a[2] - a[1]... 这样子。
        // 这一步完成后，d 数组就变成了原数组的“微分”形态。
        d[i] = a[i] - a[i - 1];
    }

    // 【处理区间修改】
    while (q--) // 循环 q 次
    {
        int l, r, x; // l区间左端点，r区间右端点，x是要增加的值
        cin >> l >> r >> x; // 读入操作。这一步绝对不能漏，漏了就全错（你之前代码就漏了）。
        
        // 【差分精髓】：区间 [l, r] 全部加 x 等价于在差分数组上做两次 O(1) 的操作：
        // 1. d[l] += x：让 l 位置产生 +x 的增量。求前缀和时，从 l 开始往后的所有元素都会自动加上 x。
        // 2. d[r+1] -= x：让 r+1 位置产生 -x 的增量。求前缀和时，从 r+1 开始往后的元素会加上 -x，
        //    刚好抵消掉前面 d[l] 带来的 +x 影响。一加一减，刚好只影响 [l, r] 区间。
        // 注意：r+1 最大可能是 n+1，由于 maxn 开了 500005，所以绝对不会越界（段错误）。
        d[l] = d[l] + x;
        d[r + 1] = d[r + 1] - x;
    }

    // 【前缀和还原】
    int cur_sum = 0; // 维护当前的前缀和（也就是修改后的 a[i]）
                     // 因为宏定义，这里的 int 实际上是 long long，不会溢出。
    for (int i = 1; i <= n; i++)
    {
        // 差分求前缀和，就是原数组。d 数组是“微分”，累加起来就是原来的 a 数组。
        // 这就像物理学里：速度的积分是位移，差分（速度）的积分（前缀和）就是原数组。
        cur_sum = cur_sum + d[i];
        
        // 输出当前元素。
        // 缺点：最后一个数字后面会多一个空格。但在绝大多数OJ上，行末空格是被允许的（不扣分）。
        // 完美主义者可以写成：if (i == n) cout << cur_sum << "\n"; else cout << cur_sum << " ";
        cout << cur_sum << " "; 
    }
    
    return 0; // 程序正常结束
}
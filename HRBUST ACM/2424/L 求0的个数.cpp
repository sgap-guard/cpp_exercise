#include <iostream>
using namespace std;
int main()
{
    int t;
    cin >> t;
    while(t--)
    {
        unsigned int n; // 定义无符号整型n，存储输入的N，匹配题目unsigned int范围
        cin >> n;       // 读取本组的数字N
        long long cnt = 0; // cnt用来记录因子5的总个数，long long防止计数溢出
        //为什么是数字5？因为5的倍数中，10的个数比5的个数多，所以只需要统计5的个数
        while(n > 0)       // 循环：不断除以5，统计5、25、125...的倍数
        {
            n = n / 5;     // 整数除法，n缩小为原来的1/5，向下取整
            cnt += n;      // 把当前得到的数量累加到总数cnt
        }
        cout << cnt << endl; // 输出本组答案，换行
    }
    return 0;           // 主函数正常结束，返回0
}


// # 重点：这段代码根本没有计算阶乘！
// 这是这道题最巧妙的地方。我们不需要算出 1×2×3×…×N 的巨大结果，直接算阶乘会溢出爆炸，所以换数学思路。

// ## 原理回顾
// 末尾的 0 来自因子 2 × 5 。
// 阶乘里因子2的数量一定比5多，末尾0的总数 = 1~N所有数字里面，因子5的总个数。

// > 比如 100! = 1×2×3×…×100
// > 我们不去算这个乘积，只去数里面能拆出来多少个5。
// > - 5,10,15,…,100：每个至少贡献1个5 → 100/5 = 20个
// > - 25,50,75,100：每个还能再多拆出1个5 → 100/25 = 4个
// > - 125>100，停止。
// > 合计 20+4 =24，就是答案。

// ## 看代码里这个while循环，就是在统计因子5
// ```cpp
// while(n > 0)
// {
//     n = n / 5;
//     cnt += n;
// }
// ```
// 拿n=100代入：
// 1. `n = 100 /5 = 20`，`cnt +=20` → cnt=20  // 统计5的倍数
// 2. `n = 20 /5 =4`，`cnt +=4` → cnt=24     // 统计25的倍数
// 3. `n =4 /5 =0`，循环结束                 // 125的倍数数量为0

// ## 对比：如果傻乎乎直接计算阶乘（❌绝对不能这么写）
// ```cpp
// long long fact = 1;
// for(int i=1;i<=n;i++){
//     fact = fact * i; // n稍微大一点，fact直接溢出，数值完全错乱
// }
// // 然后再数fact末尾有几个0
// ```
// 这个写法，n=20左右long long就存不下阶乘了，题目n最大能到unsigned int上限，直接爆炸RE/WA。

// ## 一句话总结
// 代码没有用任何变量存阶乘的乘积，它是用数学公式，直接统计阶乘的质因子5的数量，间接得到末尾0的个数。

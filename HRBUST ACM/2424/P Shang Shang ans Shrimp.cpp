#include <bits/stdc++.h>
using namespace std;

// ========== 全局数组 ==========
// P[i]：第 i 种食物的价格
// V[i]：第 i 种食物的美味值
// dp[j]：预算为 j 时能获得的最大美味值
// 数组大小：P 和 V 开到 110，因为 N <= 100
//          dp 开到 10005，因为 X < 10000
static int P[110], V[110], dp[10005];

signed main()
{
    // 开启输入输出加速
    ios::sync_with_stdio(false);
    cin.tie(0);

    // 读取测试用例数 t
    int t;
    cin >> t;

    // ========== 循环处理每组测试数据 ==========
    for (int caseNum = 1; caseNum <= t; caseNum++)
    {
        // 读取食物种类数 N 和预算 X
        int N, X;
        cin >> N >> X;

        // ========== 第 1 步：读入 N 种食物的价格和美味值 ==========
        for (int i = 1; i <= N; i++)
        {
            cin >> P[i] >> V[i];
        }

        // ========== 第 2 步：清零 dp 数组 ==========
        // 多组数据时，dp 数组可能残留上一组的值，必须清零
        // dp[j] 表示预算为 j 时的最大美味值
        for (int j = 0; j <= X; j++)
        {
            dp[j] = 0;
        }

        // ========== 第 3 步：完全背包 ==========
        // 外层枚举每种食物
        for (int i = 1; i <= N; i++)
        {
            // 内层从左到右枚举容量（从 P[i] 到 X）
            // 注意：完全背包的内层循环是"从左到右"，因为每种食物可以买多次
            for (int j = P[i]; j <= X; j++)
            {
                // 状态转移方程：
                // dp[j] = max(dp[j], dp[j - P[i]] + V[i])
                //
                // 数学含义：
                //   dp[j]：不买当前食物时的最大美味值
                //   dp[j - P[i]] + V[i]：买一个当前食物后的最大美味值
                //   取两者中较大的
                //
                // 为什么从左到右？
                //   从左到右时，dp[j - P[i]] 可能已经在本次循环中被更新过
                //   这意味着当前食物可以被重复购买，符合完全背包的要求
                dp[j] = max(dp[j], dp[j - P[i]] + V[i]);
            }
        }

        // ========== 第 4 步：输出结果 ==========
        // dp[X] 即为预算为 X 时的最大美味值
        cout << "Case #" << caseNum << ": " << dp[X] << '\n';
    }

    return 0;
}
#include <iostream>
#include <string>
using namespace std;
int main()
{
    int n;
    cin >> n;
    for(int i = 0;i < n;i++)//for循环遍历n个字符串
    {
    string s;//s表示第i个字符串
    cin >> s;//输入第i个字符串
    int len = s.size();//len表示第i个字符串的长度
    int mid = len - 2;//mid表示第i个字符串的中间部分的长度
    if(len > 10)//如果第i个字符串的长度大于10
    {cout << s[0] << mid << s[len-1] << endl;}//输出第i个字符串的第一个字符、中间部分的长度、最后一个字符
    else
    {cout << s << endl;}//输出第i个字符串
    }
    return 0;
}

#include <iostream>
#include <iomanip>
using namespace std;
int main()
{
    int n;
    while(cin >> n)//输入评委数量
    {
        double sum = 0;//sum表示所有评委的分数总和
        int maxs = 0;//maxs表示最高分
        int mins = 1000;//mins表示最低分
        for(int i = 0;i < n;i++)//for循环，从第1个评委到第n个评委
        {
            int a;//a表示第i个评委的分数
            cin >> a;//输入第i个评委的分数
            sum += a;//将第i个评委的分数加入总和
            if(a > maxs)//如果第i个评委的分数大于最高分
                maxs = a;//将最高分更新为第i个评委的分数
            if(a < mins)//如果第i个评委的分数小于最低分
                mins = a;//将最低分更新为第i个评委的分数
        }
        cout << fixed << setprecision(2) << (sum - maxs - mins) / (n - 2.0) << endl;
        //输出去掉最高分和最低分后的平均分，保留两位小数。注意，n-2.0是为了确保除法结果是浮点数。
    }
    return 0;
}
//总结
//这道题的思路是：输入评委数量，然后输入每个评委的分数，计算去掉最高分和最低分后的平均分，保留两位小数。需要注意的是，n-2.0是为了确保除法结果是浮点数。
//这道题的难点在于：如何去掉最高分和最低分，以及如何保留两位小数。
//这道题的考点在于：输入输出、循环、条件判断、浮点数运算。
//这道题的拓展在于：如果评委数量和分数都是动态输入的，如何处理？
//首先，我们需要使用while循环，将评委数量和分数都作为变量输入。
//然后，我们需要使用for循环，将每个评委的分数加入总和。
//最后，我们需要使用if语句，将最高分和最低分更新为当前评委的分数。
//最后，我们需要使用cout << fixed << setprecision(2) << (sum - maxs - mins) / (n - 2.0) << endl;，输出去掉最高分和最低分后的平均分，保留两位小数。
#include <bits/stdc++.h>
using namespace std;

// ========== 全局数组 ==========
// dp[j]：一维滚动数组，表示当前行第 j 列的最大路径和
//       在每一行更新前，dp[j] 存储的是上一行第 j 列的最大路径和
// a[j]：临时存储当前行第 j 列读入的数字

int dp[1005],a[1005];

// signed main 等价于 int main，竞赛习惯写法
signed main()
{
    // 读取数字三角形的行数 R
    int r; cin >> r;

    // ========== 逐行处理数字三角形 ==========
    // 外层循环：遍历每一行 i（从第 1 行到第 R 行）
    for (int i = 1; i <= r; i++)
    {
        // ---------- 第 1 步：读入当前行的 i 个数字 ----------
        // 第 i 行有 i 个数字，依次读入数组 a[1..i]
        for (int j = 1; j <= i; j++)
        {
            cin >> a[j];
        }

        // ---------- 第 2 步：从右往左更新 dp 数组 ----------
        // 为什么从右往左？因为 dp[j] 依赖于 dp[j-1] 和 dp[j]
        // 如果从左往右更新，dp[j-1] 会被当前行覆盖，导致使用错误的值
        // 从右往左更新，dp[j-1] 和 dp[j] 都还是上一行的值，安全
        for (int j = i; j >= 1; j--)
        {
            // 状态转移方程：
            // dp[j] = a[j] + max(dp[j-1], dp[j])
            //
            // 数学含义：
            //   要到达第 i 行第 j 列，只能从上一行的两个位置走过来：
            //   - 左上方 (i-1, j-1)：对应 dp[j-1]
            //   - 右上方 (i-1, j)  ：对应 dp[j]
            //   取两者中较大的路径和，再加上当前数字 a[j]
            //
            // 边界情况：
            //   当 j = 1 时，dp[0] = 0（初始值），表示从顶部走到第 1 列
            //   当 j = i 时，dp[i] 初始为 0（上一行没有第 i 列），
            //   所以 dp[i] = a[i] + max(dp[i-1], 0) = a[i] + dp[i-1]
            dp[j] = max(dp[j], dp[j-1]) + a[j];
        }
    }

    // ========== 第 3 步：在最后一行中找最大值 ==========
    // 最后一行有 R 个数字，对应 dp[1..R]
    // 答案是这些 dp 值中的最大值
    int ans = 0;
    for (int i = 1; i <= r; i++)
    {
        if (dp[i] > ans)
        {
            ans = dp[i];
        }
    }

    // 输出答案并换行
    cout << ans << endl;
    return 0;
}
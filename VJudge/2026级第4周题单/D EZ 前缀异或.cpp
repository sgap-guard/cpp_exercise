#include <bits/stdc++.h>
using namespace std;

// ========== 全局数组 ==========
// a[i]：存储原数组的第 i 个元素
// pfX[i]：存储前缀异或，即 a[1] ^ a[2] ^ ... ^ a[i]
// 数组大小开到 100005，因为 n <= 100000，多开几个防止越界
int a[100005], pfX[100005];

// 使用 signed main 是为了防止某些编译器将 main 的返回值隐式转换为 unsigned
// 在竞赛中这是个人习惯，效果和 int main 完全一样
signed main()
{
    // 读取数组长度 n
    int n; cin >> n;

    // 前缀异或的初始边界：S[0] = 0
    // 数学意义：前 0 个元素的异或和为 0（异或的恒等元）
    pfX[0] = 0;

    // ========== 预处理前缀异或 ==========
    // 遍历数组，读入 a[i] 的同时计算前缀异或
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];

        // 前缀异或递推公式：S[i] = S[i-1] ^ a[i]
        // 利用异或的结合律，把前面所有元素的异或结果与当前元素异或
        pfX[i] = pfX[i-1] ^ a[i];
    }

    // 读取询问次数 m
    int m; cin >> m;

    // ========== 处理每组询问 ==========
    for (int q = 1; q <= m; q++)
    {
        // 读取询问区间 [l, r]
        int l, r; cin >> l >> r;

        // 利用前缀异或公式计算区间异或：
        // a[l] ^ a[l+1] ^ ... ^ a[r] = S[r] ^ S[l-1]
        // 数学推导：
        //   S[r] = a[1] ^ ... ^ a[l-1] ^ a[l] ^ ... ^ a[r]
        //   S[l-1] = a[1] ^ ... ^ a[l-1]
        //   S[r] ^ S[l-1] = (a[1] ^ ... ^ a[l-1]) 出现两次，异或后抵消为 0
        //                  只剩下 a[l] ^ ... ^ a[r]
        int result = pfX[r] ^ pfX[l-1];

        // 输出区间异或结果并换行
        cout << result << endl;
    }
    return 0;
}
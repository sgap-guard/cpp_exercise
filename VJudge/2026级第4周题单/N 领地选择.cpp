#include <bits/stdc++.h>
using namespace std;

// ========== 全局数组 ==========
// S[i][j]：二维前缀和，表示从 (1,1) 到 (i,j) 的矩形内所有元素的和
// A[i][j]：存储原始矩阵的每个元素
// 数组大小开到 1005，因为题目 N, M <= 1000，多开几个防止越界
// static 修饰全局数组，限制链接属性（单文件程序中可省略）
static long long S[1005][1005], A[1005][1005];

signed main()
{
    // 读入 N（行数）、M（列数）、C（首都边长）
    int n, m, c;
    cin >> n >> m >> c;

    // 二维前缀和的边界初始化（全局数组默认就是 0，这行可省略）
    S[0][0] = 0;

    // ========== 第 1 步：读入矩阵并计算二维前缀和 ==========
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            // 读入当前位置的价值
            cin >> A[i][j];

            // 二维前缀和递推公式：
            // S[i][j] = S[i-1][j] + S[i][j-1] - S[i-1][j-1] + A[i][j]
            //
            // 数学含义：
            //   S[i-1][j]：上方矩形的和
            //   S[i][j-1]：左方矩形的和
            //   S[i-1][j-1]：左上方矩形的和被多算了一次，减去
            //   A[i][j]：当前格子本身
            S[i][j] = S[i-1][j] + S[i][j-1] - S[i-1][j-1] + A[i][j];
        }
    }

    // ========== 第 2 步：枚举所有可能的左上角 ==========
    // MaxSum 初始化为负无穷，因为价值可能为负数
    // -1e18 是一个足够小的负数，也可以用 LLONG_MIN
    long long MaxSum = -1e18;

    // 记录最优解的左上角坐标，初始为 (1,1)
    int BestX(1), BestY(1);

    // 枚举所有可能的左上角 (i, j)
    // i 的范围：1 到 n-c+1（保证正方形不越界）
    // j 的范围：1 到 m-c+1
    for (int i = 1; i <= n - c + 1; i++)
    {
        for (int j = 1; j <= m - c + 1; j++)
        {
            // 计算当前正方形的右下角坐标
            int x2 = i + c - 1;
            int y2 = j + c - 1;

            // ========== 二维前缀和公式计算 C×C 正方形的和 ==========
            // Sum = S[x2][y2] - S[i-1][y2] - S[x2][j-1] + S[i-1][j-1]
            //
            // 数学含义：
            //   S[x2][y2]：从 (1,1) 到 (x2,y2) 的整个矩形的和
            //   S[i-1][y2]：上方的多余部分，减去
            //   S[x2][j-1]：左方的多余部分，减去
            //   S[i-1][j-1]：左上方被多减了一次，加回来
            long long sum = S[x2][y2] - S[i-1][y2] - S[x2][j-1] + S[i-1][j-1];

            // 如果当前正方形的和大于已知最大值，更新
            if (sum > MaxSum)
            {
                MaxSum = sum;
                BestX = i;
                BestY = j;
            }
        }
    }

    // ========== 第 3 步：输出最优解的左上角坐标 ==========
    cout << BestX << " " << BestY << endl;
    return 0;
}
#include <bits/stdc++.h>
using namespace std;

int diff[100005];

signed main()
{
    // 读取输入：N 头奶牛，第 I 头最高，高度为 H，R 条"看见"关系
    int N, I, H, R;
    cin >> N >> I >> H >> R;

    // 差分数组的边界初始化（实际上全局数组默认就是 0，这行可以省略）
    diff[0] = 0;

    // 用 set 存储已经处理过的关系对 (A, B)，用于去重
    // 防止同一条 "A 看见 B" 关系被重复处理，导致区间被多次减 1
    set<pair<int, int>> seen;

    // ========== 处理 R 条"看见"关系 ==========
    for (int k = 1; k <= R; k++)
    {
        // 读取当前关系：奶牛 A 看见奶牛 B
        int A, B;
        cin >> A >> B;

        // 确保 A < B，方便后续处理区间 (A, B)
        // 因为"看见"关系是对称的：A 看见 B 等价于 B 看见 A
        if (A > B)
        {
            swap(A, B);
        }

        // 去重：如果 (A, B) 已经处理过，直接跳过
        // 否则重复处理会导致区间 (A, B) 被多次减 1，结果错误
        if (seen.find({A, B}) != seen.end())
        {
            continue;
        }

        // 标记 (A, B) 已处理
        seen.insert({A, B});

        // ========== 差分数组核心操作 ==========
        // 题意：A 和 B 之间的所有奶牛高度必须严格小于 A 的高度
        // 为了最大化所有奶牛的高度，让中间奶牛恰好比 A 矮 1
        // 即：区间 (A, B) 内所有奶牛高度减 1
        //
        // 差分操作：
        //   diff[A + 1]--  表示从 A+1 开始，高度减量 +1
        //   diff[B]++      表示从 B 开始，高度减量撤销（恢复原值）
        //
        // 这样处理后，只有区间 [A+1, B-1] 内的奶牛高度被减 1
        diff[A + 1]--;
        diff[B]++;
    }

    // ========== 前缀和还原 + 输出结果 ==========
    // current 记录当前位置的"高度减量"的累积值
    int current = 0;

    // 遍历每头奶牛（编号从 1 到 N）
    for (int i = 1; i <= N; i++)
    {
        // 前缀和：累加差分数组，得到当前位置的总减量
        // 数学意义：current = -（第 i 头奶牛被减去的次数）
        current += diff[i];

        // 计算第 i 头奶牛的最大可能高度
        // 初始高度为 H（假设所有奶牛都是最高的）
        // 减去 current 的绝对值（因为 current 是负的，H + current 相当于 H - |current|）
        int height = H + current;

        // 特判：第 I 头奶牛是最高奶牛，高度必须严格等于 H
        // 题目保证第 I 头奶牛的高度是 H，且它不会被任何关系影响
        if (i == I)
        {
            height = H;
        }

        // 输出第 i 头奶牛的最大可能高度
        cout << height << endl;
    }

    return 0;
}
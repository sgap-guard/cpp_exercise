#include<bits/stdc++.h>
using namespace std;

int arr[2005][2005];

int main()
{
    // 开启输入输出加速
    // 关闭 C 和 C++ 标准流的同步，避免 cin/cout 混用时的性能损耗
    ios::sync_with_stdio(false);
    
    // 解绑 cin 和 cout，避免每次输入前自动刷新输出缓冲区，提升 I/O 速度
    cin.tie(0); cout.tie(0);
    
    // 读取网格大小 n 和地毯数量 m
    int n, m;
    cin >> n >> m;
    
    // 循环 m 次，处理每个地毯的覆盖操作
    for (int k = 1; k <= m; k++)
    {
        // 读取当前地毯的左上角 (x1, y1) 和右下角 (x2, y2)
        int x1, y1, x2, y2;
        cin >> x1 >> y1 >> x2 >> y2;
        
        // ========== 二维差分核心操作（容斥原理） ==========
        // 在矩形左上角 (x1, y1) 加上 1
        // 这会导致从 (x1, y1) 到整个网格右下角的所有格子前缀和都加 1
        arr[x1][y1]++;
        
        // 在 (x2+1, y1) 减去 1
        // 抵消掉矩形下方区域（第 x2+1 行及以下）多加的 1
        arr[x2+1][y1]--;
        
        // 在 (x1, y2+1) 减去 1
        // 抵消掉矩形右方区域（第 y2+1 列及以右）多加的 1
        arr[x1][y2+1]--;
        
        // 在 (x2+1, y2+1) 加上 1
        // 右下角区域被减了两次（行和列各减了一次），需要加回来一次
        arr[x2+1][y2+1]++;
    }
    
    // ========== 二维前缀和还原 ==========
    // 遍历每一个格子，用二维前缀和公式还原出每个格子实际被覆盖的次数
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            // 二维前缀和递推公式：
            // A[i][j] = A[i-1][j] + A[i][j-1] - A[i-1][j-1] + D[i][j]
            // 其中 D[i][j] 是差分数组的当前值，A 是还原后的原数组
            // 注意：这里直接在原数组上原地修改，因为 arr[i][j] 之后不会再被其他格子用到
            arr[i][j] = arr[i-1][j] + arr[i][j-1] - arr[i-1][j-1] + arr[i][j];
            
            // 输出当前格子被地毯覆盖的总次数
            cout << arr[i][j] << " ";
        }
        
        // 每输出完一行后换行
        // 使用 '\n' 而不是 endl，因为 endl 会强制刷新缓冲区，影响性能
        cout << '\n';
    }
    
    // 程序正常结束
    return 0;
}
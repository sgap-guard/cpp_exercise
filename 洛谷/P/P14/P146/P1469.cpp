#include<iostream>
using namespace std;
int main()
{
    ios::sync_with_stdio(false);//关闭同步流，提高效率。此语句必须放在cin.tie(0)之前。
    //什么是同步流？
    //1. 同步流是指输入流和输出流是同步的，即输入流和输出流是同时进行的。
    //2. 同步流的效率较低，因为输入流和输出流是同时进行的，需要等待输出流完成，才能继续输入流。
    cin.tie(0);
    //将输入流与cout绑定，提高效率。

    int n;
    cin >> n;//输入n，表示输入。
    long long ans = 0;//初始化答案为0。
    for(int i = 1;i <= n;i++)//遍历n个数。
    {
        long long x;//输入一个数x。
        cin >> x;
        ans ^= x;//将答案与x异或，得到新的答案。
        //异或操作的性质是：两个数的二进制表示按位异或结果就是两个数的二进制表示按位异或，得到的结果。
    }
    cout << ans << endl;//输出答案。
    //答案就是n个数的异或结果。
    return 0;
}
//总结：
//本题的思路是：
//1. 输入n，表示输入。
//2. 遍历n个数，将每个数与答案异或，得到新的答案。
//3. 输出答案。
//4. 返回0。
//所涉及的知识点是;
//1. 异或操作。
//2. 循环遍历。
//3. 输入输出。
//4. 返回值。

//什么是ios::sync_with_stdio(false)和cin.tie(0)？
//1. 关闭同步流，提高效率。
//2. 将输入流与cout绑定，提高效率。

